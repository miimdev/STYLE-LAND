CREATE FUNCTION public.create_profile() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  INSERT INTO public.profiles (user_id,full_name) VALUES (NEW.id,coalesce(NEW.raw_user_meta_data->>'full_name','')) ON CONFLICT DO NOTHING;
  RETURN NEW;
END $$;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.create_profile();

-- An order is a single transaction: the server rechecks prices, coupon, shipping and stock.
-- It records a TEST order only; neither payment option charges money or dispatches goods.
CREATE FUNCTION public.place_order(p_items jsonb,p_customer jsonb,p_shipping_method text,p_payment_method text,p_coupon text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  uid uuid := auth.uid(); item jsonb; variant record; oid uuid; code text;
  qty integer; v_subtotal integer := 0; v_discount integer := 0; v_shipping integer := 0;
  percent_off integer := 0; product_identifier bigint;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'AUTH_REQUIRED'; END IF;
  IF jsonb_typeof(p_items) IS DISTINCT FROM 'array' OR jsonb_array_length(p_items) NOT BETWEEN 1 AND 50 THEN RAISE EXCEPTION 'INVALID_CART'; END IF;
  IF jsonb_typeof(p_customer) IS DISTINCT FROM 'object'
     OR char_length(trim(coalesce(p_customer->>'fullName',''))) NOT BETWEEN 3 AND 100
     OR coalesce(p_customer->>'phone','') !~ '^09[0-9]{9}$'
     OR coalesce(p_customer->>'postalCode','') !~ '^[0-9]{10}$'
     OR char_length(trim(coalesce(p_customer->>'province',''))) NOT BETWEEN 2 AND 80
     OR char_length(trim(coalesce(p_customer->>'city',''))) NOT BETWEEN 2 AND 80
     OR char_length(trim(coalesce(p_customer->>'address',''))) NOT BETWEEN 10 AND 500 THEN RAISE EXCEPTION 'INVALID_CUSTOMER'; END IF;
  IF p_shipping_method NOT IN ('post','courier','free') OR p_payment_method NOT IN ('online','cod') THEN RAISE EXCEPTION 'INVALID_METHOD'; END IF;
  code := 'ST' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
  INSERT INTO public.orders(user_id,tracking_code,customer,shipping_method,payment_method)
    VALUES(uid,code,p_customer,p_shipping_method,p_payment_method) RETURNING id INTO oid;
  FOR item IN SELECT value FROM jsonb_array_elements(p_items) LOOP
    IF coalesce(item->>'productId','') !~ '^[0-9]{1,10}$' OR coalesce(item->>'quantity','') !~ '^[0-9]{1,2}$' THEN RAISE EXCEPTION 'INVALID_ITEM'; END IF;
    product_identifier := (item->>'productId')::bigint; qty := (item->>'quantity')::integer;
    IF qty NOT BETWEEN 1 AND 10 THEN RAISE EXCEPTION 'INVALID_QUANTITY'; END IF;
    SELECT pv.id,pv.stock,p.name,p.price INTO variant FROM public.product_variants pv
      JOIN public.products p ON p.id = pv.product_id
      WHERE pv.product_id = product_identifier AND pv.color = item->>'color' AND pv.size = item->>'size' FOR UPDATE OF pv;
    IF NOT FOUND OR variant.stock < qty THEN RAISE EXCEPTION 'OUT_OF_STOCK'; END IF;
    UPDATE public.product_variants SET stock = stock - qty WHERE id = variant.id;
    INSERT INTO public.order_items(order_id,product_id,product_name,color,size,quantity,unit_price)
      VALUES(oid,product_identifier,variant.name,item->>'color',item->>'size',qty,variant.price);
    v_subtotal := v_subtotal + variant.price * qty;
  END LOOP;
  IF p_coupon IS NOT NULL AND trim(p_coupon) <> '' THEN
    SELECT c.discount_percent INTO percent_off FROM public.coupons c WHERE c.code = upper(trim(p_coupon)) AND c.active
      AND (c.starts_at IS NULL OR c.starts_at <= now()) AND (c.expires_at IS NULL OR c.expires_at > now());
    IF NOT FOUND THEN RAISE EXCEPTION 'INVALID_COUPON'; END IF;
    v_discount := floor(v_subtotal::numeric * percent_off / 100);
  END IF;
  IF p_shipping_method = 'free' THEN
    IF v_subtotal < 1600000 THEN RAISE EXCEPTION 'FREE_SHIPPING_UNAVAILABLE'; END IF;
    v_shipping := 0;
  ELSIF p_shipping_method = 'post' THEN v_shipping := 85000;
  ELSE v_shipping := 125000; END IF;
  UPDATE public.orders SET subtotal = v_subtotal, discount = v_discount, shipping_cost = v_shipping,
    total = v_subtotal - v_discount + v_shipping, coupon = nullif(upper(trim(coalesce(p_coupon,''))), '') WHERE id = oid;
  UPDATE public.products p SET stock = (SELECT coalesce(sum(v.stock),0) FROM public.product_variants v WHERE v.product_id=p.id)
    WHERE p.id IN (SELECT (entry->>'productId')::bigint FROM jsonb_array_elements(p_items) entry);
  RETURN jsonb_build_object('orderId',oid,'trackingCode',code,'total',v_subtotal-v_discount+v_shipping,'status','test');
END $$;
REVOKE ALL ON FUNCTION public.place_order(jsonb,jsonb,text,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.place_order(jsonb,jsonb,text,text,text) TO authenticated;
