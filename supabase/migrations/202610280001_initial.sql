-- Store schema. User-owned tables are only visible to their owner.
CREATE TABLE public.categories (
  slug text PRIMARY KEY, name text NOT NULL, image text NOT NULL, local_image text NOT NULL
);
CREATE TABLE public.brands (slug text PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE public.products (
  id bigint PRIMARY KEY, name text NOT NULL, brand text NOT NULL REFERENCES public.brands(slug),
  category text NOT NULL REFERENCES public.categories(slug),
  gender text NOT NULL CHECK (gender IN ('women','men','kids','unisex')),
  price integer NOT NULL CHECK (price >= 0), old_price integer CHECK (old_price IS NULL OR old_price >= price),
  discount_percent smallint NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 100),
  colors jsonb NOT NULL DEFAULT '[]', sizes jsonb NOT NULL DEFAULT '[]',
  images jsonb NOT NULL DEFAULT '[]', local_images jsonb NOT NULL DEFAULT '[]',
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0), rating numeric(2,1) NOT NULL DEFAULT 0,
  reviews_count integer NOT NULL DEFAULT 0, description text NOT NULL DEFAULT '',
  specs jsonb NOT NULL DEFAULT '{}', tags jsonb NOT NULL DEFAULT '[]', created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_category_idx ON public.products(category);
CREATE INDEX products_gender_idx ON public.products(gender);
CREATE TABLE public.product_variants (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  color text NOT NULL, color_hex text NOT NULL, size text NOT NULL,
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0), UNIQUE(product_id,color,size)
);
CREATE TABLE public.profiles (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL DEFAULT '', phone text NOT NULL DEFAULT '', addresses jsonb NOT NULL DEFAULT '[]',
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.reviews (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL, display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 80),
  rating smallint NOT NULL CHECK (rating BETWEEN 1 AND 5), comment text NOT NULL CHECK (char_length(comment) BETWEEN 3 AND 1000),
  seed_key text UNIQUE, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.wishlists (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,product_id)
);
CREATE TABLE public.cart_items (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  color text NOT NULL, size text NOT NULL, quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,product_id,color,size)
);
CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  tracking_code text NOT NULL UNIQUE, customer jsonb NOT NULL,
  shipping_method text NOT NULL CHECK (shipping_method IN ('post','courier','free')),
  payment_method text NOT NULL CHECK (payment_method IN ('online','cod')),
  subtotal integer NOT NULL DEFAULT 0, discount integer NOT NULL DEFAULT 0, shipping_cost integer NOT NULL DEFAULT 0,
  total integer NOT NULL DEFAULT 0, coupon text, status text NOT NULL DEFAULT 'test',
  payment_status text NOT NULL DEFAULT 'not_paid', created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL, color text NOT NULL, size text NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0), unit_price integer NOT NULL CHECK (unit_price >= 0)
);
CREATE TABLE public.blog_posts (
  id bigint PRIMARY KEY, slug text NOT NULL UNIQUE, title text NOT NULL, category text NOT NULL,
  excerpt text NOT NULL, image text NOT NULL, local_image text NOT NULL, read_time integer NOT NULL,
  published_at date NOT NULL DEFAULT CURRENT_DATE, body jsonb NOT NULL DEFAULT '[]', published boolean NOT NULL DEFAULT true
);
CREATE TABLE public.newsletter_subscribers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(), email text NOT NULL UNIQUE CHECK (char_length(email) BETWEEN 3 AND 254),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.coupons (
  code text PRIMARY KEY, discount_percent smallint NOT NULL CHECK (discount_percent BETWEEN 1 AND 100),
  active boolean NOT NULL DEFAULT true, starts_at timestamptz, expires_at timestamptz
);

